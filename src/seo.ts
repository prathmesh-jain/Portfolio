import { education, experience, profile, projects, toolbox, type Project } from './data/content'

/**
 * Everything search engines and link previews need for one route.
 * Pure data: used by the build-time prerender (written into the HTML)
 * and on the client (kept in sync when navigating).
 */
export interface Seo {
  title: string
  description: string
  canonical: string
  image: string
  imageAlt: string
  type: 'website' | 'article' | 'profile'
  noindex?: boolean
  jsonLd: Record<string, unknown>[]
}

const SITE = profile.site
const abs = (path: string) => (path.startsWith('http') ? path : `${SITE}${path}`)
const DEFAULT_IMAGE = abs('/profile.jpg')
/** 1200x630 preview cards generated by scripts/og-cards.mjs */
const ogCard = (name: string) => abs(`/og/${name}.jpg`)

const clip = (text: string, max = 158) => {
  if (text.length <= max) return text
  const cut = text.slice(0, max)
  return `${cut.slice(0, cut.lastIndexOf(' ')).replace(/[,;:.\s]+$/, '')}…`
}

const personId = `${SITE}/#person`
const websiteId = `${SITE}/#website`

const currentJob = experience.find((j) => !j.end)

const person = {
  '@type': 'Person',
  '@id': personId,
  name: profile.name,
  url: `${SITE}/`,
  image: DEFAULT_IMAGE,
  email: `mailto:${profile.email}`,
  jobTitle: currentJob?.role ?? profile.role,
  ...(currentJob ? { worksFor: { '@type': 'Organization', name: currentJob.company } } : {}),
  address: { '@type': 'PostalAddress', addressLocality: 'Mumbai', addressCountry: 'IN' },
  alumniOf: { '@type': 'CollegeOrUniversity', name: education.school.split(',')[0] },
  sameAs: [profile.links.github, profile.links.linkedin, profile.links.leetcode],
  knowsAbout: toolbox.flatMap((t) => t.items).slice(0, 30),
}

const homeSeo = (): Seo => ({
  title: `${profile.name} – ${profile.role} in Mumbai`,
  description: clip(
    `${profile.name} builds multi-agent AI systems and full-stack products with Python, FastAPI, LangGraph and React. Projects include ${projects
      .slice(0, 3)
      .map((p) => p.title)
      .join(', ')} and more.`,
  ),
  canonical: `${SITE}/`,
  image: ogCard('home'),
  imageAlt: `${profile.name}, ${profile.role}`,
  type: 'profile',
  jsonLd: [
    {
      '@context': 'https://schema.org',
      '@type': 'WebSite',
      '@id': websiteId,
      url: `${SITE}/`,
      name: profile.name,
      inLanguage: 'en',
      publisher: { '@id': personId },
    },
    {
      '@context': 'https://schema.org',
      '@type': 'ProfilePage',
      url: `${SITE}/`,
      mainEntity: person,
      hasPart: projects.map((p) => ({ '@type': 'CreativeWork', name: p.title, url: `${SITE}/work/${p.slug}` })),
    },
  ],
})

const projectSeo = (p: Project): Seo => {
  const url = `${SITE}/work/${p.slug}`
  const image = ogCard(p.slug)
  return {
    title: `${p.seoTitle} | ${profile.name}`,
    description: clip(`${p.tagline} ${p.summary}`),
    canonical: url,
    image,
    imageAlt: `${p.title}: ${p.tagline}`,
    type: 'article',
    jsonLd: [
      {
        '@context': 'https://schema.org',
        '@type': 'SoftwareApplication',
        name: p.title,
        description: p.tagline,
        url: p.links.live ?? url,
        image,
        applicationCategory: p.platform === 'Android' ? 'FinanceApplication' : 'BusinessApplication',
        operatingSystem: p.platform,
        keywords: p.stack.join(', '),
        ...(p.links.github ? { sameAs: p.links.github } : {}),
        author: p.team ? { '@type': 'Organization', name: `${p.title} team`, member: { '@id': personId } } : { '@id': personId },
      },
      {
        '@context': 'https://schema.org',
        '@type': 'Article',
        headline: `${p.title}: ${p.tagline}`,
        description: clip(p.summary),
        image,
        url,
        mainEntityOfPage: url,
        author: { '@type': 'Person', '@id': personId, name: profile.name, url: `${SITE}/` },
        isPartOf: { '@id': websiteId },
      },
      {
        '@context': 'https://schema.org',
        '@type': 'BreadcrumbList',
        itemListElement: [
          { '@type': 'ListItem', position: 1, name: 'Home', item: `${SITE}/` },
          { '@type': 'ListItem', position: 2, name: p.title, item: url },
        ],
      },
    ],
  }
}

const notFoundSeo = (path: string): Seo => ({
  title: `Page not found | ${profile.name}`,
  description: 'This page doesn’t exist. Head back to the homepage to see my work.',
  canonical: `${SITE}${path}`,
  image: ogCard('home'),
  imageAlt: `${profile.name}, ${profile.role}`,
  type: 'website',
  noindex: true,
  jsonLd: [],
})

export const findProject = (pathname: string) => {
  const m = pathname.match(/^\/work\/([\w-]+)\/?$/)
  return m ? projects.find((p) => p.slug === m[1]) ?? null : null
}

export function seoFor(pathname: string): Seo {
  if (pathname === '/' || pathname === '') return homeSeo()
  const project = findProject(pathname)
  return project ? projectSeo(project) : notFoundSeo(pathname)
}

/** Every URL that should exist as a real HTML file (and be listed in the sitemap). */
export const routes = ['/', ...projects.map((p) => `/work/${p.slug}`)]

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

/** The <head> tags for a route, as an HTML string (used at build time). */
export function seoHeadHtml(seo: Seo): string {
  const tags = [
    `<title>${esc(seo.title)}</title>`,
    `<meta name="description" content="${esc(seo.description)}" />`,
    `<meta name="robots" content="${seo.noindex ? 'noindex, follow' : 'index, follow, max-image-preview:large'}" />`,
    `<link rel="canonical" href="${esc(seo.canonical)}" />`,
    `<meta property="og:site_name" content="${esc(profile.name)}" />`,
    `<meta property="og:locale" content="en_IN" />`,
    `<meta property="og:type" content="${seo.type}" />`,
    `<meta property="og:title" content="${esc(seo.title)}" />`,
    `<meta property="og:description" content="${esc(seo.description)}" />`,
    `<meta property="og:url" content="${esc(seo.canonical)}" />`,
    `<meta property="og:image" content="${esc(seo.image)}" />`,
    `<meta property="og:image:alt" content="${esc(seo.imageAlt)}" />`,
    `<meta property="og:image:type" content="image/jpeg" />`,
    `<meta property="og:image:width" content="1200" />`,
    `<meta property="og:image:height" content="630" />`,
    `<meta name="twitter:card" content="summary_large_image" />`,
    `<meta name="twitter:title" content="${esc(seo.title)}" />`,
    `<meta name="twitter:description" content="${esc(seo.description)}" />`,
    `<meta name="twitter:image" content="${esc(seo.image)}" />`,
    ...seo.jsonLd.map(
      (d) => `<script type="application/ld+json" data-seo>${JSON.stringify(d).replace(/</g, '\\u003c')}</script>`,
    ),
  ]
  return tags.join('\n    ')
}
